/**
 * Таблицы перевода первичных баллов в тестовые (100-балльные) баллы ЕГЭ 2026.
 * Источник: официальные распоряжения Рособрнадзора / ФИПИ на 2026 год.
 *
 * Используется для прогноза итогового результата симулятора:
 *   ученик решил X из Y первичных → показываем «примерно Z тестовых баллов ЕГЭ».
 *
 * ВАЖНО: наш симулятор проверяет только 1-ю часть. Прогноз итогового балла
 * делаем в предположении «средний ответ на 2-ю часть» — обычно это 50-60%
 * от максимума 2-й части.
 */

export interface ScoreTable {
  /** Массив [первичный балл, тестовый балл] в порядке возрастания. */
  entries: Array<[number, number]>;
  /** Максимум первичных баллов всего экзамена. */
  maxPrimary: number;
}

