export const SCORE_TABLES: Record<string, ScoreTable> = {
  russian: RUSSIAN_TABLE,
  "social-multi": SOCIAL_TABLE,
  "math-multi": MATH_TABLE,
};

/**
 * Переводит первичный балл в тестовый для конкретного предмета.
 * Если между значениями таблицы — интерполирует линейно.
 */
export function primaryToTest(subjectKey: string, primary: number): number {
  const table = SCORE_TABLES[subjectKey];
  if (!table) return 0;

  const clamped = Math.max(0, Math.min(table.maxPrimary, primary));
  const rounded = Math.round(clamped);

  const entry = table.entries.find(([p]) => p === rounded);
  if (entry) return entry[1];

  // fallback: линейно
  return Math.round((clamped / table.maxPrimary) * 100);
}

/**
 * Прогноз итогового тестового балла ЕГЭ по результату только 1-й части.
 *
 * Логика:
 *   1. Считаем долю правильных ответов в 1-й части (part1Fraction).
 *   2. Предполагаем, что 2-ю часть ученик напишет с такой же долей успеха.
 *   3. Считаем предполагаемый общий первичный балл.
 *   4. Переводим в тестовый по таблице.
 *
 * Возвращаем диапазон [низкая оценка, высокая оценка] — 2-ю часть на реальном
 * экзамене может как повезти, так и не очень, поэтому даём вилку ±10%.
 */
export function forecastTotalScore(
  subjectKey: string,
  primaryPart1: number,
  maxPrimaryPart1: number
): { min: number; expected: number; max: number } {
  const table = SCORE_TABLES[subjectKey];
  if (!table) return { min: 0, expected: 0, max: 0 };

  const part1Fraction = maxPrimaryPart1 > 0 ? primaryPart1 / maxPrimaryPart1 : 0;
  const part2Max = table.maxPrimary - maxPrimaryPart1;

  // «Средний» ученик: та же доля успеха на 2-й части
  const expectedPart2Primary = part2Max * part1Fraction;
  const expectedTotal = primaryPart1 + expectedPart2Primary;

  // Вилка ±10% от максимума 2-й части (эмпирика — обычно так)
  const spread = part2Max * 0.10;

  return {
    min: primaryToTest(subjectKey, expectedTotal - spread),
    expected: primaryToTest(subjectKey, expectedTotal),
    max: primaryToTest(subjectKey, expectedTotal + spread),
  };
}
