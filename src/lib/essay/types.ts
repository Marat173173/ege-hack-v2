/**
 * Схема разбора сочинения ЕГЭ по К1-К12.
 * Официальные критерии ФИПИ 2026, максимум 25 баллов.
 *
 * Используется:
 *   - на сервере: как схема JSON от Claude в /api/essay/review
 *   - на клиенте: как тип для отображения разбора в ExamResult/EssayResult
 */

export type KriterionCode =
  | "K1" | "K2" | "K3" | "K4" | "K5" | "K6"
  | "K7" | "K8" | "K9" | "K10" | "K11" | "K12";

/** Официальный максимум по каждому критерию (ФИПИ 2026). */
export const KRITERION_MAX: Record<KriterionCode, number> = {
  K1: 1,  // Формулировка проблем исходного текста
  K2: 6,  // Комментарий к проблеме (4 балла за примеры + 2 за связь)
  K3: 1,  // Отражение позиции автора
  K4: 1,  // Отношение к позиции автора и обоснование
  K5: 2,  // Смысловая цельность, речевая связность, последовательность
  K6: 2,  // Точность и выразительность речи
  K7: 3,  // Орфографические нормы
  K8: 3,  // Пунктуационные нормы
  K9: 2,  // Грамматические нормы
  K10: 2, // Речевые нормы
  K11: 1, // Соблюдение этических норм
  K12: 1, // Соблюдение фактологической точности
};

export const KRITERION_MAX_TOTAL = Object.values(KRITERION_MAX).reduce((a, b) => a + b, 0);
// = 25

