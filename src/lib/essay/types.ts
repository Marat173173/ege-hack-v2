/** Один пункт разбора: оценка + пояснение + рекомендация. */
export interface KriterionScore {
  code: KriterionCode;
  score: number;         // балл, полученный учеником
  max: number;           // максимум по этому критерию
  comment: string;       // почему такой балл
  advice?: string;       // конкретный совет «как докрутить» (если балл не максимальный)
}

/** Полный разбор сочинения. */
export interface EssayReview {
  criteria: KriterionScore[];    // все 12 критериев по порядку
  totalScore: number;             // сумма набранных
  maxScore: number;               // 25 (константа)
  summary: string;                // короткая общая оценка на 1-3 предложения
  quickTips: string[];            // 2-4 ключевых рекомендации из самых слабых мест
  strongPoints: string[];         // 1-3 сильных стороны работы (для мотивации)
}
