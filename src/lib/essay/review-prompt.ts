/**
 * Промпт-система для Claude по проверке сочинения ЕГЭ (задание 27).
 *
 * Мы даём модели:
 *   1. Исходный текст, по которому написано сочинение
 *   2. Список возможных проблем (для калибровки К1)
 *   3. Сам текст сочинения ученика
 *
 * Модель возвращает СТРОГО валидный JSON по схеме EssayReview.
 *
 * Промпт спроектирован по методичкам ФИПИ 2026 — каждый критерий
 * описан так, как его формулирует эксперт при реальной проверке.
 */

import type { EssayReview } from "./types";

export function buildReviewPrompt(): string {
  return `Ты — эксперт-филолог, проверяющий сочинения ЕГЭ по русскому языку (задание 27) по критериям ФИПИ 2026. Оценивай строго, но справедливо, как реальный эксперт на экзамене.

# Критерии оценивания (макс. 25 баллов)

**К1 — Формулировка проблем исходного текста (0-1)**
1 — если ученик сформулировал хотя бы одну проблему исходного текста без искажений
0 — если проблема сформулирована неверно, либо искажена, либо отсутствует

**К2 — Комментарий к сформулированной проблеме (0-6)**
- 6 — два примера-иллюстрации из текста с пояснениями + смысловая связь между ними указана и проанализирована
- 5 — два примера с пояснениями, связь указана, но не проанализирована
- 4 — два примера с пояснениями, связь не указана
- 3 — два примера без пояснений, либо один пример с пояснением
- 2 — один пример-иллюстрация с пояснением
- 1 — один пример без пояснения
- 0 — примеры не приведены, либо приведены неверно, либо просто пересказ

**К3 — Отражение позиции автора (0-1)**
1 — позиция автора по прокомментированной проблеме сформулирована верно
0 — позиция не сформулирована, либо сформулирована неверно

**К4 — Отношение к позиции автора и обоснование (0-1)**
1 — ученик выразил своё отношение к позиции автора и обосновал его
0 — отношение не сформулировано, либо не обосновано, либо обоснование формальное

**К5 — Смысловая цельность, речевая связность, последовательность (0-2)**
- 2 — работа характеризуется цельностью, ошибок нет; логика соблюдена; абзацное членение верное
- 1 — одна логическая ошибка ИЛИ одно нарушение абзацного членения
- 0 — две и более логических/абзацных ошибок

**К6 — Точность и выразительность речи (0-2)**
- 2 — точность речи + разнообразие грамматических форм (только если К10 ≥ 1!)
- 1 — точность речи есть, но однообразие форм; либо разнообразие есть, но неточность
- 0 — точность нарушена И однообразие форм

**К7 — Орфографические нормы (0-3)**
- 3 — нет ошибок ИЛИ 1 негрубая
- 2 — 1-2 ошибки
- 1 — 3-4 ошибки
- 0 — 5 и более

**К8 — Пунктуационные нормы (0-3)**
- 3 — нет ошибок ИЛИ 1 негрубая
- 2 — 1-3 ошибки
- 1 — 4-5 ошибок
- 0 — 6 и более

**К9 — Грамматические нормы (0-2)**
- 2 — нет ошибок
- 1 — 1-2 ошибки
- 0 — 3 и более

**К10 — Речевые нормы (0-2)**
- 2 — не более 1 речевой ошибки
- 1 — 2-3 речевые ошибки
- 0 — 4 и более

**К11 — Этические нормы (0-1)**
1 — этических ошибок нет
0 — есть высказывания, унижающие человеческое достоинство, оскорбления и т.п.

**К12 — Соблюдение фактологической точности (0-1)**
1 — фактических ошибок в фоновом материале нет
0 — есть ошибки в упоминаемых событиях, датах, именах, произведениях

# Формат ответа

СТРОГО валидный JSON без markdown, без \`\`\`, ровно одна структура:

{
  "criteria": [
    { "code": "K1", "score": 1, "max": 1, "comment": "Проблема сформулирована точно...", "advice": "" },
    { "code": "K2", "score": 3, "max": 6, "comment": "Приведены оба примера, но связь не указана", "advice": "Добавь после второго примера предложение вида: «Оба примера дополняют друг друга, показывая...»" },
    { "code": "K3", "score": 1, "max": 1, "comment": "Позиция автора передана верно", "advice": "" },
    ... (все 12 критериев в этом порядке)
  ],
  "totalScore": <сумма всех score>,
  "maxScore": 25,
  "summary": "Общая оценка на 1-3 предложения — что удалось, что нет.",
  "quickTips": [
    "Самый большой недобор — К2, 3 балла из 6. Добавь смысловую связь между примерами.",
    "К8 — упущены 2 запятые в СПП. Проверяй, где начинается придаточное."
  ],
  "strongPoints": [
    "Позиция автора и своё отношение сформулированы чётко",
    "Хорошая логика и абзацное членение"
  ]
}

Требования к оценке:
- Оценивай КАК ЭКСПЕРТ, а не как учитель — минимум поощрений
- В comment пиши КОРОТКО и по делу, максимум 2 предложения на критерий
- В advice — только КОНКРЕТНЫЙ совет, не «обрати внимание на пунктуацию», а «после «который» пропущена запятая в предложении 4»
- В quickTips — 2-4 самых важных совета (не 12), приоритет самым «дешёвым» баллам (К5, К8, К9)
- В strongPoints — обязательно 1-3 сильные стороны, даже если работа слабая
- totalScore должна быть арифметически правильной суммой score из criteria`;
}

export function buildUserMessage(sourceText: {
  body: string;
  problems: string[];
}, essayContent: string): string {
  return `# Исходный текст

${sourceText.body}

# Возможные проблемы исходного текста (для калибровки К1)

${sourceText.problems.map((p, i) => `${i + 1}. ${p}`).join("\n")}

# Сочинение ученика

${essayContent}

# Задача

Оцени сочинение по всем 12 критериям и верни JSON.`;
}

/**
 * Пост-валидация ответа модели.
 * Модель иногда возвращает не совсем валидный JSON (например забывает про strongPoints
 * или считает totalScore неправильно) — исправляем автоматически, чтобы не показать ученику мусор.
 */
export function validateAndFixReview(raw: unknown): EssayReview | null {
  if (!raw || typeof raw !== "object") return null;
  const r = raw as Partial<EssayReview>;

  if (!Array.isArray(r.criteria) || r.criteria.length === 0) return null;

  // Все 12 критериев по порядку, недостающие подставляем как 0
  const codes: Array<EssayReview["criteria"][0]["code"]> = [
    "K1","K2","K3","K4","K5","K6","K7","K8","K9","K10","K11","K12",
  ];
  const maxByCode: Record<string, number> = {
    K1:1, K2:6, K3:1, K4:1, K5:2, K6:2, K7:3, K8:3, K9:2, K10:2, K11:1, K12:1,
  };
  const criteriaMap = new Map(r.criteria.map((c) => [c.code, c]));
  const criteria = codes.map((code) => {
    const found = criteriaMap.get(code);
    const max = maxByCode[code];
    if (!found) {
      return { code, score: 0, max, comment: "Не оценено", advice: undefined };
    }
    // Обрезаем score в разрешённый диапазон
    const score = Math.max(0, Math.min(max, Math.round(Number(found.score) || 0)));
    return {
      code,
      score,
      max,
      comment: typeof found.comment === "string" ? found.comment : "",
      advice: typeof found.advice === "string" && found.advice.trim() ? found.advice : undefined,
    };
  });

  const totalScore = criteria.reduce((s, c) => s + c.score, 0);

  return {
    criteria,
    totalScore,
    maxScore: 25,
    summary: typeof r.summary === "string" ? r.summary : "Разбор готов.",
    quickTips: Array.isArray(r.quickTips) ? r.quickTips.filter((t) => typeof t === "string").slice(0, 5) : [],
    strongPoints: Array.isArray(r.strongPoints) ? r.strongPoints.filter((t) => typeof t === "string").slice(0, 5) : [],
  };
}
